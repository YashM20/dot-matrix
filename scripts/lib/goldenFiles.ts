/**
 * The golden files on disk (issue #76): one `goldens/<board>.json` per board, each `{ about, presets }` with the
 * same 1-space JSON as before, so two boards' changes never touch the same file. A preset lives in the file of the
 * first board that lists it (the order of `uniquePresets`). Every preset is on a board, so there is no catch-all
 * file. Node built-ins only.
 *
 * Readers call `readGoldens()` (the union of every board file). `scripts/golden.ts` is the only writer.
 */
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import type { Goldens } from './goldenKey'

export const GOLDENS_DIR = 'goldens'
/** Where the presets used to live in one file. Now only a generated, gitignored index for postbuild (`writeGoldenIndex`). */
export const LEGACY_FILE = `${GOLDENS_DIR}/hashes.json`
/** Files in goldens/ that are not board files: the legacy index and the IR / noise snapshots. No board may take these ids. */
export const NOT_BOARDS = new Set(['hashes', 'ir-glsl', 'noise', 'noise-glsl'])

const about = (board: string) =>
  `FNV-1a 32 of the sorted quantized dot list per preset on the ${board} board (scripts/golden.ts). Re-baseline with \`pnpm golden\` when a change is intended.`
export const boardFile = (board: string) => `${GOLDENS_DIR}/${board}.json`
const serialize = (board: string, presets: Goldens) => JSON.stringify({ about: about(board), presets }, null, 1) + '\n'

/** Board ids that have a file in goldens/ (sorted). */
export function goldenBoards(): string[] {
  if (!existsSync(GOLDENS_DIR)) return []
  return readdirSync(GOLDENS_DIR).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5)).filter(b => !NOT_BOARDS.has(b)).sort()
}

export interface GoldenSet {
  /** Every preset of every board file, board files in name order. */
  presets: Goldens
  /** preset id → the board file it was read from */
  boardOf: Map<string, string>
  /** presets found in more than one board file: `id (a.json, b.json)` */
  dupes: string[]
  files: number
}

/** The union of every `goldens/<board>.json`. */
export function readGoldens(): GoldenSet {
  const presets: Goldens = {}, boardOf = new Map<string, string>(), dupes: string[] = [], boards = goldenBoards()
  for (const b of boards) {
    for (const [id, row] of Object.entries((JSON.parse(readFileSync(boardFile(b), 'utf8')) as { presets: Goldens }).presets)) {
      if (boardOf.has(id)) { dupes.push(`${id} (${boardOf.get(id)}.json, ${b}.json)`); continue }
      presets[id] = row
      boardOf.set(id, b)
    }
  }
  return { presets, boardOf, dupes, files: boards.length }
}

/**
 * Write one file per board, in the given board and preset order. A file is rewritten only when its bytes change;
 * a board file whose board is gone is deleted. Returns the board ids written and removed.
 */
export function writeGoldens(byBoard: Map<string, Goldens>): { written: string[]; removed: string[] } {
  const bad = [...byBoard.keys()].filter(b => NOT_BOARDS.has(b) || !/^[a-z0-9][a-z0-9-]*$/.test(b))
  if (bad.length) throw new Error(`goldens: board id(s) ${bad.join(', ')} can't be a golden file name (reserved: ${[...NOT_BOARDS].join(', ')})`)
  const written: string[] = [], removed: string[] = []
  for (const [b, presets] of byBoard) {
    const f = boardFile(b), text = serialize(b, presets)
    if (existsSync(f) && readFileSync(f, 'utf8') === text) continue
    writeFileSync(f, text)
    written.push(b)
  }
  for (const b of goldenBoards()) if (!byBoard.has(b)) { rmSync(boardFile(b)); removed.push(b) }
  return { written, removed }
}

/**
 * `goldens/hashes.json` as the one-file shape, generated from the board files and gitignored. Only
 * `scripts/site/postbuild.ts` still reads that path (its OG cache key); the build (`vite.config.ts`) runs
 * `npx tsx scripts/lib/goldenFiles.ts --index` just before it.
 */
export function writeGoldenIndex(): void {
  const { presets } = readGoldens()
  writeFileSync(LEGACY_FILE, JSON.stringify({ about: 'Generated by scripts/lib/goldenFiles.ts from goldens/<board>.json for the build. Do not edit or commit.', presets }, null, 1) + '\n')
}

if (/[\\/]scripts[\\/]lib[\\/]goldenFiles\.ts$/.test(process.argv[1] ?? '') && process.argv.includes('--index')) writeGoldenIndex()
