/** Quantize trained float weights to the shipped Int8 asset (per-row scales) and write it as a TS module. */
import { writeFileSync } from 'node:fs'
import type { NcaAsset } from '../../src/engine/nca'
import { views, type Dims } from './core'

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
export function bytesBase64(b: Uint8Array): string {
  let s = ''
  for (let i = 0; i < b.length; i += 3) {
    const n = (b[i] << 16) | ((b[i + 1] ?? 0) << 8) | (b[i + 2] ?? 0)
    s += B64[(n >> 18) & 63] + B64[(n >> 12) & 63] + (i + 1 < b.length ? B64[(n >> 6) & 63] : '=') + (i + 2 < b.length ? B64[n & 63] : '=')
  }
  return s
}
function quant(m: Float32Array, rows: number, cols: number): { b64: string; scales: number[] } {
  const q = new Int8Array(rows * cols), scales: number[] = []
  for (let r = 0; r < rows; r++) {
    let mx = 0
    for (let c = 0; c < cols; c++) mx = Math.max(mx, Math.abs(m[r * cols + c]))
    const s = mx / 127 || 1e-8
    // store the scale rounded to 6 significant digits, and quantize against that exact value
    const sr = Number(s.toPrecision(6))
    scales.push(sr)
    for (let c = 0; c < cols; c++) q[r * cols + c] = Math.max(-127, Math.min(127, Math.round(m[r * cols + c] / sr)))
  }
  return { b64: bytesBase64(new Uint8Array(q.buffer)), scales }
}
export function toAsset(d: Dims, flat: Float32Array, extra: { name: string; seedAt: [number, number]; fire: number; grown: number; meta?: NcaAsset['meta'] }): NcaAsset {
  const { w1, b1, w2 } = views(d, flat), q1 = quant(w1, d.HID, 3 * d.C), q2 = quant(w2, d.HID, d.C)
  return {
    name: extra.name, channels: d.C, hidden: d.HID, w: d.W, h: d.H, seedAt: extra.seedAt, fire: extra.fire, grown: extra.grown,
    w1: q1.b64, s1: q1.scales, b1: Array.from(b1, v => Number(v.toPrecision(6))), w2: q2.b64, s2: q2.scales, meta: extra.meta,
  }
}
export function writeAsset(file: string, exportName: string, a: NcaAsset): void {
  const body = `/**
 * Growing-NCA weights: ${a.name}. Generated by scripts/nca/train.ts — do not edit by hand.
 * ${a.channels} channels, ${a.hidden} hidden, ${a.w}×${a.h} grid; Int8 rows with per-row scales.
 */
import type { NcaAsset } from '../../engine/nca'

export const ${exportName}: NcaAsset = {
${Object.entries(a).filter(([, v]) => v !== undefined).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}
}
`
  writeFileSync(file, body)
}
