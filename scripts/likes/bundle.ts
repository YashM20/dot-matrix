/**
 * Bundles `src/lib/likes/site.ts` (the program key, the IR parser it uses, the widget uids) plus the seed program
 * keys into `api/_lib/gen/site.mjs` for the likes functions (#169). Vercel compiles function files with tsc and
 * doesn't bundle them, so they can't import `src/` directly.
 *
 *   npx tsx scripts/likes/bundle.ts           → write api/_lib/gen/site.mjs and site.d.mts
 *   npx tsx scripts/likes/bundle.ts --check   → exit 1 if the committed files are stale (also in the likes checks)
 *
 * Run it after changing the IR parser, the share checks, the seed programs or the widget list.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { EXAMPLES } from '../../src/components/dwitter/examples'
import { programKey } from '../../src/lib/likes/site'

const ROOT = join(import.meta.dirname, '../..')
export const OUT = 'api/_lib/gen/site.mjs', TYPES = 'api/_lib/gen/site.d.mts'
const HEAD = '// Generated by `npx tsx scripts/likes/bundle.ts` from src/lib/likes/site.ts. Do not edit.\n'

const DTS = `${HEAD}export declare function programKey(x: unknown): Promise<string>
export declare const PROGRAM_KEY_RE: RegExp
export declare const WIDGET_UIDS: ReadonlySet<string>
/** Keys of the 8 seed programs (src/components/dwitter/examples.ts): they never expire. */
export declare const SEED_KEYS: readonly string[]
`

/** The bundle and its types as they should be. */
export async function build(): Promise<{ js: string; dts: string }> {
  // esbuild comes with tsx (pnpm doesn't link it at the top level, so resolve it from tsx)
  const esbuild = createRequire(createRequire(join(ROOT, 'package.json')).resolve('tsx/package.json'))('esbuild') as typeof import('esbuild')
  const out = await esbuild.build({ entryPoints: [join(ROOT, 'src/lib/likes/site.ts')], absWorkingDir: ROOT, bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', legalComments: 'none', logLevel: 'warning', write: false })
  const js = out.outputFiles[0].text
  const seeds = await Promise.all(EXAMPLES.map(e => programKey(e)))
  return { js: `${HEAD}${js.replace(/\r\n/g, '\n')}export const SEED_KEYS = ${JSON.stringify(seeds)};\n`, dts: DTS }
}

const read = (f: string) => (existsSync(join(ROOT, f)) ? readFileSync(join(ROOT, f), 'utf8').replace(/\r\n/g, '\n') : '')

/** True when the committed bundle matches a fresh one. */
export async function bundleCurrent(): Promise<boolean> {
  const b = await build()
  return read(OUT) === b.js && read(TYPES) === b.dts
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('scripts/likes/bundle.ts')) {
  if (process.argv.includes('--check')) {
    const ok = await bundleCurrent()
    console.log(ok ? '✓ likes: api/_lib/gen/site.mjs is current' : '✗ likes: api/_lib/gen/site.mjs is stale: run npx tsx scripts/likes/bundle.ts')
    if (!ok) process.exit(1)
  } else {
    const b = await build()
    writeFileSync(join(ROOT, OUT), b.js); writeFileSync(join(ROOT, TYPES), b.dts)
    console.log(`wrote ${OUT} (${(b.js.length / 1024).toFixed(1)} kB) and ${TYPES}`)
  }
}
