/**
 * Permanent widget uids (docs/SHARE-PLAN.md §3). `src/widgets/ids.json` maps a slug (the preset id at the time
 * it was assigned) to its uid. It is **append-only**: an entry is never rewritten or removed, a uid is never
 * reused (even when its widget is deleted), and a renamed widget keeps its uid through `cardAliases`
 * (`src/widgets/manifest.ts`). `src/widgets/catalog.ts` is generated from it: `[slug, uid, board]` per current
 * widget, the lazy lookup behind `/widget/<key>/` and `/<uid>`.
 *
 *   npx tsx scripts/widgets/ids.ts --assign   → give every widget without a uid a fresh one, rewrite catalog.ts
 *   npx tsx scripts/widgets/ids.ts --check    → exit 1 if a widget lacks a uid, an id changed / collided, or
 *                                               catalog.ts is stale (also run by `pnpm verify`: `idsChecks`)
 *
 * After adding widgets (a new board, a merge): run `--assign` and commit both files.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { boards } from '../../src/widgets'
import { boardIds, cardAliases, resolveCardId } from '../../src/widgets/manifest'
import { isReservedSegment, isSlug, isUid, makeUid, type CatalogRow } from '../../src/site/routes'

const IDS = 'src/widgets/ids.json', CATALOG = 'src/widgets/catalog.ts'
type Assert = (name: string, cond: boolean, detail?: string) => void

export const readIds = (file = IDS): Record<string, string> => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {})

/** Every widget once, on the first board it appears on (manifest order). */
export function widgetBoards(): { slug: string; board: string }[] {
  const seen = new Set<string>(), out: { slug: string; board: string }[] = []
  for (const b of boards) for (const p of b.items) if (!seen.has(p.id)) { seen.add(p.id); out.push({ slug: p.id, board: b.id }) }
  return out
}

/** A widget's uid: its own entry, else the entry of an old slug that now resolves to it. */
export function uidOf(slug: string, ids: Record<string, string>): string | undefined {
  if (ids[slug]) return ids[slug]
  for (const old in ids) if (old !== slug && resolveCardId(old) === slug) return ids[old]
}

export function catalogRows(ids = readIds()): CatalogRow[] {
  return widgetBoards().map(({ slug, board }) => [slug, uidOf(slug, ids) ?? '', board] as const)
}
export function catalogSource(rows: readonly CatalogRow[]): string {
  return [
    '// Generated by `npx tsx scripts/widgets/ids.ts --assign` from src/widgets/ids.json and the boards. Do not edit.',
    "import type { CatalogRow } from '../site/routes'",
    '',
    '/** `[slug, uid, board]` for every widget, board order: the lazy lookup behind `/widget/<key>/` and `/<uid>` (src/site/routes.ts). */',
    'export const catalog: readonly CatalogRow[] = [',
    ...rows.map(([s, u, b]) => `  ['${s}', '${u}', '${b}'],`),
    ']',
    '',
  ].join('\n')
}
const idsSource = (ids: Record<string, string>) => `{\n${Object.entries(ids).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')}\n}\n`

/** Append a uid for every widget without one; never touches an existing entry. Returns the slugs it added. */
export function assign(): string[] {
  const ids = readIds(), taken = new Set(Object.values(ids)), added: string[] = []
  for (const { slug } of widgetBoards()) {
    if (uidOf(slug, ids)) continue
    const uid = makeUid(b => globalThis.crypto.getRandomValues(b), taken)
    ids[slug] = uid; taken.add(uid); added.push(slug)
  }
  writeFileSync(IDS, idsSource(ids))
  writeFileSync(CATALOG, catalogSource(catalogRows(ids)))
  return added
}

/** ids.json as committed at `ref`, if git and the ref exist. */
function idsAt(ref: string): Record<string, string> | undefined {
  try { return JSON.parse(execFileSync('git', ['show', `${ref}:${IDS}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })) } catch { return undefined }
}

export function idsChecks(check: Assert) {
  const ids = readIds(), widgets = widgetBoards()
  const missing = widgets.filter(w => !uidOf(w.slug, ids)).map(w => w.slug)
  check('share: every widget has a permanent uid (src/widgets/ids.json)', !missing.length, missing.length ? `${missing.join(', ')}: run npx tsx scripts/widgets/ids.ts --assign` : `${widgets.length} widgets`)
  const uids = Object.values(ids), bad = uids.filter(u => !isUid(u))
  check('share: uids are unique and 8-char Crockford base-32 with ≥ 2 digits and 1 letter', !bad.length && new Set(uids).size === uids.length, bad.join(', '))
  // append-only: every entry committed before (HEAD, main) is still there with the same value
  const changed: string[] = []
  for (const ref of ['HEAD', 'main', 'origin/main']) {
    const before = idsAt(ref)
    if (before) for (const [k, v] of Object.entries(before)) if (ids[k] !== v) changed.push(`${ref}:${k} ${v} → ${ids[k] ?? 'removed'}`)
  }
  check('share: ids.json is append-only (no committed uid changed or removed)', !changed.length, changed.slice(0, 5).join('; '))
  const src = existsSync(CATALOG) ? readFileSync(CATALOG, 'utf8').replace(/\r\n/g, '\n') : ''
  const fresh = src === catalogSource(catalogRows(ids))
  check('share: src/widgets/catalog.ts matches ids.json and the boards', fresh, fresh ? '' : 'run npx tsx scripts/widgets/ids.ts --assign')
  const slugs = widgets.map(w => w.slug), badSlug = slugs.filter(s => !isSlug(s))
  check('share: slugs are kebab-case, ≤ 32 chars and never uid-shaped', !badSlug.length, badSlug.join(', '))
  const badBoard = boardIds.filter(isReservedSegment)
  check('share: board ids avoid the uid pattern and reserved segments (widget, embed, r, og, @…)', !badBoard.length, badBoard.join(', '))
  const golden = Object.keys((JSON.parse(readFileSync('goldens/hashes.json', 'utf8')) as { presets: Record<string, unknown> }).presets)
  const lost = golden.filter(id => !slugs.includes(resolveCardId(id)))
  check('share: every golden id still resolves to a widget (presets + cardAliases)', !lost.length, lost.join(', '))
  const loops = Object.entries(cardAliases).filter(([from, to]) => from === to || !slugs.includes(to) || slugs.includes(from))
  check('share: cardAliases point old slugs at current widgets', !loops.length, loops.map(([a, b]) => `${a}→${b}`).join(', '))
}

if (/[\\/]scripts[\\/]widgets[\\/]ids\.ts$/.test(process.argv[1] ?? '')) {
  if (process.argv.includes('--assign')) {
    const added = assign()
    console.log(added.length ? `ids: ${added.length} new uid(s): ${added.map(s => `${s}=${readIds()[s]}`).join(', ')}` : 'ids: every widget already has a uid')
  }
  let failures = 0
  idsChecks((name, ok, detail) => { console[ok ? 'log' : 'error'](`${ok ? '✓' : '✗'} ${name}${detail ? ` — ${detail}` : ''}`); if (!ok) failures++ })
  if (failures) process.exit(1)
}
