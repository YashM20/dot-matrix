/**
 * The credits list (#54): writes docs/CREDITS.md from every preset's `credit` (src/widgets/types.ts, DESIGN.md
 * "Credit line") grouped by source, plus the code ports listed in THIRD-PARTY-NOTICES.md. It opens with the concept
 * credit (`conceptCredit` in src/widgets/blurbs.ts): Henry Li's ESP-Mosaico screens, where the project started.
 *
 *   npx tsx scripts/site/credits.ts           → checks, then write docs/CREDITS.md
 *   npx tsx scripts/site/credits.ts --check   → checks only; exit 1 if docs/CREDITS.md is stale (in `pnpm check`)
 *
 * Checks: grouping and sorting on a made-up credited set (never shipped), stale detection, every `source` an
 * https URL and every `by` non-empty, the lazy-loader list (`loadCredits`, for ABOUT) equal to the eager one.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { boards } from '../../src/widgets'
import { creditEntries, creditProblems, groupCredits, loadCredits, type CreditEntry, type CreditGroup } from '../../src/widgets/credits'
import { checker } from '../lib/check'
import { conceptCredit as cc } from '../../src/widgets/blurbs'

/** The opening section: where the project started. */
const concept = (): string[] => [
  '## The concept',
  '',
  `This project started from the ESP-Mosaico concept screens for a 480 × 480 OLED device by [${cc.by}](${cc.profile}) (\`${cc.handle}\` on X), posted on X on 20 Aug 2026:`,
  '',
  `- [First post](${cc.posts[0]})`,
  `- [Second post](${cc.posts[1]})`,
  '',
  'What came from his posts:',
  '',
  `- The first seven boards (${cc.boards.map(b => `\`/${b}/\``).join(', ')}) rebuild his reference sheets, kept in \`public/images/\`, most of them under his X media ids as file names ([BLOCK-INVENTORY.md](BLOCK-INVENTORY.md)). Those boards show this credit under their blurb.`,
  '- The idea the engine grew from: a whole interface drawn in dots on a dense square matrix.',
  "- The 480 in Dot/480, the engine's codename: his device is 480 × 480.",
  '',
]

const OUT = 'docs/CREDITS.md', NOTICES = 'THIRD-PARTY-NOTICES.md'
const FIX = 'run npx tsx scripts/site/credits.ts'
const check = process.argv.includes('--check')

/** One `## Author` section of THIRD-PARTY-NOTICES.md with the articles in its table. */
interface PortSection { author: string; articles: { title: string; url: string }[] }

/** The `## ` sections of the notices and the `| [title](url) | … |` rows of their tables. */
function parsePorts(md: string): PortSection[] {
  const out: PortSection[] = []
  for (const line of md.replace(/\r\n/g, '\n').split('\n')) {
    const h = /^## (.+)$/.exec(line)
    if (h) { out.push({ author: h[1].trim(), articles: [] }); continue }
    const row = /^\| \[([^\]]+)\]\(([^)]+)\) \|/.exec(line)
    if (row && out.length) out[out.length - 1].articles.push({ title: row[1], url: row[2] })
  }
  return out.filter(s => s.articles.length)
}

const esc = (s: string) => s.replace(/([\\[\]*_`<>])/g, '\\$1')
const same = (a: string[], b: string[]) => a.length === b.length && a.every((x, i) => x === b[i])

/** A card's line; its own authors show when the cards of its source don't all credit the same people. */
function cardLine(c: CreditGroup['cards'][number], uniform: boolean): string {
  let s = `- ${esc(c.name)} (\`${c.card}\`), board \`/${c.board}/\``
  if (!uniform) s += `, by ${esc(c.by.join(', '))}`
  if (c.note) s += `: ${esc(c.note)}`
  return s
}

function render(groups: CreditGroup[], ports: PortSection[]): string {
  const L = [
    '# Credits',
    '',
    `<!-- Generated by \`npx tsx scripts/site/credits.ts\` from each card's \`credit\` and ${NOTICES}: do not edit. -->`,
    '',
    ...concept(),
    '## Cards',
    '',
    "The work a card is built on, grouped by source. Each card's page shows the same credit under its blurb.",
    '',
  ]
  if (!groups.length) L.push('No card carries a credit yet.', '')
  for (const g of groups) {
    L.push(`### [${esc(g.title)}](${g.source})`, '', `By ${esc(g.by.join(', '))}.`, '')
    const uniform = g.cards.every(c => same(c.by, g.cards[0].by))
    for (const c of g.cards) L.push(cardLine(c, uniform))
    L.push('')
  }
  L.push('## Code ports', '', `Code ported into the engine, by article. What each port covers, and the credits the articles give, are in [${NOTICES}](../${NOTICES}).`, '')
  for (const s of ports) {
    L.push(`### ${esc(s.author)}`, '')
    for (const a of s.articles) L.push(`- [${esc(a.title)}](${a.url})`)
    L.push('')
  }
  return L.join('\n').replace(/\n+$/, '\n')
}

/** True when the file on disk differs from what the generator writes (line endings aside). */
const isStale = (want: string, have: string | undefined) => have === undefined || have.replace(/\r\n/g, '\n') !== want

const { assert, done } = checker('credits')

// A made-up credited set: the same source under two titles and on two boards, a card on two boards, a second
// source whose title sorts first only case-insensitively, and the entries fed in a shuffled order.
const S1 = 'https://example.com/articles/zoom/', S2 = 'https://example.org/apple/'
const fake: CreditEntry[] = [
  { board: 'oldschool', card: 'old-b', name: 'Old B', credit: { by: ['Inigo Quilez'], title: 'Zoom', source: S1 } },
  { board: 'fractals', card: 'frac-c', name: 'Frac C', credit: { by: ['Ada'], title: 'apple', source: S2 } },
  { board: 'fractals', card: 'frac-a', name: 'Frac A', credit: { by: ['oneshade', 'Inigo Quilez'], title: 'Zoom!', source: S1, note: 'remixed' } },
  { board: 'alpha', card: 'frac-a', name: 'Frac A', credit: { by: ['oneshade', 'Inigo Quilez'], title: 'Zoom', source: S1 } },
]
const fg = groupCredits(fake)
assert('credits: grouping puts every card of a source in one group, a card on two boards once per board',
  fg.length === 2 && fg[1].source === S1 && fg[1].cards.length === 3 && fg[0].cards.length === 1, fg.map(g => `${g.title}: ${g.cards.length}`).join(', '))
assert('credits: a source takes its most used title and ranks authors by cards credited',
  fg[1].title === 'Zoom' && same(fg[1].by, ['Inigo Quilez', 'oneshade']), `${fg[1].title} by ${fg[1].by.join(', ')}`)
assert('credits: sources sort by title case-insensitively, cards by board then id',
  fg[0].title === 'apple' && same(fg[1].cards.map(c => `${c.board}/${c.card}`), ['alpha/frac-a', 'fractals/frac-a', 'oldschool/old-b']))
assert('credits: output is the same for any input order',
  JSON.stringify(groupCredits([...fake].reverse())) === JSON.stringify(fg) && render(groupCredits([fake[2], fake[0], fake[3], fake[1]]), []) === render(fg, []))
const fakeMd = render(fg, [])
assert("credits: each card's authors show when its source's cards credit different people, and a note follows",
  fakeMd.includes('- Frac A (`frac-a`), board `/fractals/`, by oneshade, Inigo Quilez: remixed\n') && fakeMd.includes('- Old B (`old-b`), board `/oldschool/`, by Inigo Quilez\n')
  && fakeMd.includes('- Frac C (`frac-c`), board `/fractals/`\n'))
assert('credits: the problem check flags http, bare and malformed sources and an empty by',
  creditProblems([
    { ...fake[0], credit: { ...fake[0].credit, source: 'http://example.com/' } },
    { ...fake[0], credit: { ...fake[0].credit, source: 'example.com/x' } },
    { ...fake[0], credit: { ...fake[0].credit, by: [] } },
    { ...fake[0], credit: { ...fake[0].credit, by: ['Ada', ' '] } },
  ]).length === 4 && !creditProblems(fake).length)

// The real presets.
const entries = creditEntries(boards)
const groups = groupCredits(entries)
const problems = creditProblems(entries)
assert('credits: every source is an https URL and every by is non-empty', !problems.length, problems.length ? problems.join('; ') : `${entries.length} credited card(s), ${groups.length} source(s)`)
const lazy = await loadCredits()
assert("credits: loadCredits() over the manifest's lazy loaders equals the eager list", JSON.stringify(lazy) === JSON.stringify(groups))
const ports = parsePorts(readFileSync(NOTICES, 'utf8'))
const badPorts = ports.flatMap(s => s.articles).filter(a => !a.url.startsWith('https://'))
assert(`credits: ${NOTICES} parses into sections of https articles`, ports.length > 0 && !badPorts.length,
  badPorts.length ? badPorts.map(a => a.url).join(', ') : ports.map(s => `${s.author}: ${s.articles.length}`).join(', '))

const want = render(groups, ports)
const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : undefined
assert('credits: stale detection ignores line endings and catches a changed list',
  !isStale(want, want.replace(/\n/g, '\r\n')) && isStale(want, render(groupCredits([...entries, ...fake]), ports)) && isStale(want, undefined))
if (check) { const stale = isStale(want, have); assert(`credits: ${OUT} is current`, !stale, stale ? `${OUT} is stale: ${FIX}` : '') }
else if (isStale(want, have)) { writeFileSync(OUT, want); console.log(`wrote ${OUT}`) }
else console.log(`${OUT} is current`)
done(check ? `${OUT} is current` : '')
