/**
 * GLSL ES 3.0 prelude of the IR noise pack: `ir_noise`, `ir_fbm`, `ir_turb`, `ir_voronoi`, mirroring `noise2`,
 * `fbm2`, `turb2` and `voronoiMode` (noise/gradient.ts, noise/voronoi.ts) op for op.
 *  - Hash: `ir_ih(int a, int b, uint s)` is `ihash` in `uint` arithmetic (uint(int) keeps the bits; GLSL `int()`
 *    truncates toward zero like JS `| 0`, so seeds agree), with its own finaliser copy `ir_nfm` (the core `hash`
 *    helper's `ir_fmix` may sit in the same program).
 *  - Lattice `ivec2(floor(p))`, the same 8-gradient table in the same order, the same quintic fade, the octave
 *    rotation mat2(.8, .6, −.6, .8) written out, octave seeds `s ^ o·0x9e3779b9`.
 *  - Voronoi: the same 3×3 + pruned ±2 ring search in the same scan order; 16-bit feature coordinates (exact in float32).
 * The GPU runs in float32, so parity is a tolerance, not bits: a floor right at a lattice line can land on the other
 * side (scripts/webgl.ts counts these as flips). Keep IR noise inputs within |x|, |y| < 4096; past that the f32
 * spacing (≥ 2⁻¹¹) visibly quantises the fade.
 */
