/**
 * Hero numerals (#269): three hand-drawn bitmap faces, 14 dots tall, one bitmap pixel per lattice dot. They replace
 * the Scale2x upscale of the 5×7 font for numerals, whose diagonals stepped two and three dots and whose corners
 * came out uneven. Every face keeps one stroke weight, cuts corners on a 45°, and has tabular digits.
 * - `twin`: two-dot stroke, digits 10 wide, corners cut by two dots, bars on rows 0-1, 6-7 and 12-13.
 * - `fine`: one-dot stroke, digits 8 wide, corners cut by one dot.
 * - `condensed`: two-dot stroke, digits 8 wide, flat sides, only the outer corner dot dropped.
 * A 45° stroke is three dots per row in the two-dot faces and one in `fine`, so it reads as wide as the straight ones.
 */
export type HeroFace = 'twin' | 'fine' | 'condensed'

/** Glyph height in dots (the smooth face's height, so a face swaps in at the same lattice). */
export const HERO_H = 14
/** Dots between glyphs. */
const GAP = 2

const rows = (s: string) => s.trim().split(/\s+/)
/** The glyph turned half a turn (a 9 from a 6). */
const turn = (g: string[]) => [...g].reverse().map(r => [...r].reverse().join(''))
/** `%`: two round dots `n` wide (corners off; a ring when `ring`) top-left and bottom-right, and a 45° slash on the diagonals x + y in `band`. */
function percent(w: number, n: number, band: number[], ring = false): string[] {
  const b = Array.from({ length: HERO_H }, (_, y) => Array.from({ length: w }, (_, x) => (band.includes(x + y) ? '#' : '.')))
  const blob = (x0: number, y0: number) => {
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      const corner = (x === 0 || x === n - 1) && (y === 0 || y === n - 1)
      if (!corner && !(ring && x === 1 && y === 1)) b[y0 + y][x0 + x] = '#'
    }
  }
  blob(0, 0); blob(w - n, HERO_H - n)
  return b.map(r => r.join(''))
}
