/** True when every character of `s` is in the face (digits, `. : % - +`, space). */
export const heroCovers = (face: HeroFace, s: string) => s.length > 0 && [...s].every(ch => ch in FACES[face])
/** `s` set in the face: `HERO_H` rows of `#` (dot) and `.`, glyphs `GAP` dots apart. */
export function heroRows(face: HeroFace, s: string): string[] {
  const glyphs = [...s].map(ch => FACES[face][ch] ?? FACES[face][' '])
  return Array.from({ length: HERO_H }, (_, y) => glyphs.map(g => g[y]).join('.'.repeat(GAP)))
}
/** Width of `s` in dots. */
export const heroWidth = (face: HeroFace, s: string) => heroRows(face, s)[0].length
