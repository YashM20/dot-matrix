export const GLYPH_W = 5, GLYPH_H = 7, GLYPH_ADVANCE = 6
export interface TextOptions {
  /** Font pixel → dots. A pair scales x and y independently (tall display numerals use [2,3]). */
  scale?: number | [number, number]
  /**
   * Display weight: each glyph is upscaled 2× with Scale2x, so strokes are two dots thick and
   * diagonals/curves step one dot at a time (the reference hero numerals). Glyphs become 10×14.
   */
  smooth?: boolean
}
/** Glyph box and advance in font pixels for a weight. */
export const glyphMetrics = (opts: TextOptions = {}) => (opts.smooth ? { w: 10, h: 14, advance: 12 } : { w: GLYPH_W, h: GLYPH_H, advance: GLYPH_ADVANCE })
/** Width in font pixels of a string (glyphs + gaps, no trailing gap). */
export const textWidth = (str: string, opts: TextOptions = {}) => { const m = glyphMetrics(opts); return Math.max(1, [...str].length * m.advance - (m.advance - m.w)) }
export const hasGlyph = (ch: string) => ch.toUpperCase() in bitmapFont

/** Scale2x (EPX): 2× upscale that rounds diagonals instead of doubling their stairs. */
export function scale2x(bits: boolean[][]): boolean[][] {
  const h = bits.length, w = bits[0]?.length ?? 0, at = (x: number, y: number) => (x >= 0 && y >= 0 && x < w && y < h ? bits[y][x] : false)
  const out = Array.from({ length: h * 2 }, () => new Array<boolean>(w * 2).fill(false))
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const p = at(x, y), a = at(x, y - 1), b = at(x + 1, y), c = at(x - 1, y), d = at(x, y + 1)
    out[y * 2][x * 2] = c === a && c !== d && a !== b ? a : p
    out[y * 2][x * 2 + 1] = a === b && a !== c && b !== d ? b : p
    out[y * 2 + 1][x * 2] = d === c && d !== b && c !== a ? c : p
    out[y * 2 + 1][x * 2 + 1] = b === d && b !== a && d !== c ? d : p
  }
  return out
}
const smoothCache = new Map<string, boolean[][]>()
export function glyph(ch: string, opts: TextOptions = {}): boolean[][] {
  const base = bitmapFont[ch.toUpperCase()] ?? bitmapFont[' ']
  if (!opts.smooth) return base
  let g = smoothCache.get(ch); if (!g) { g = scale2x(base); smoothCache.set(ch, g) }
  return g
}

/**
 * Text as a field over a box that is exactly `textWidth(str)×glyph height` font pixels (times scale).
 * Sample it with the layout helper `textAt()` so one font pixel lands on `scale` whole dots;
 * sampling it into a box of any other size resamples the glyphs and breaks the pixel grid.
 */
export function textField(str: string, opts: TextOptions = {}): Field {
  const chars = [...str]; const m = glyphMetrics(opts), width = textWidth(str, opts)
  const glyphs = chars.map(ch => glyph(ch, opts))
  return (u, v) => {
    const x = Math.min(width - 1, Math.floor(u * width)), y = Math.min(m.h - 1, Math.floor(v * m.h))
    const g = glyphs[Math.floor(x / m.advance)]
    return g?.[y]?.[x % m.advance] ? 1 : 0
  }
}
