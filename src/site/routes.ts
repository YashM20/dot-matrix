/**
 * Widget identity and URLs (docs/SHARE-PLAN.md §3). Pure and DOM-free, so `scripts/verify.ts` checks it in
 * Node. Every widget has two keys and both open it: the **slug** (its preset id, readable, renamable through
 * `cardAliases`) and the **uid** (8 characters of lowercase Crockford base-32, permanent, `src/widgets/ids.json`).
 *
 * URL grammar, one ordered route table (a new kind of page is one line):
 *   [/@<scope>]/widget/<slug | uid>/   the widget page (canonical: `/widget/<slug>/`)
 *   /<uid>                             the shortest share link (a uid can never be a board id: verify checks)
 *   ?card=<slug | uid>                 the old one-card link, kept forever
 * The scope is empty today (the site's own widgets); `/@acme/widget/timer/` names an org's widget later
 * without touching any existing link. Slugs are unique within a scope, uids everywhere.
 */

/** Lowercase Crockford base-32: no i, l, o, u, so a uid reads aloud and survives handwriting. */
export const UID_ALPHABET = '0123456789abcdefghjkmnpqrstvwxyz'
export const UID_LENGTH = 8
/** Exactly 8 alphabet characters with at least two digits and one letter, so no word-like slug can ever match. */
export const UID_RE = /^(?=(?:[^0-9]*[0-9]){2})(?=.*[a-z])[0-9a-hjkmnp-tv-z]{8}$/
export const isUid = (s: string): boolean => UID_RE.test(s)
/** Slugs: kebab-case, ≤ 32 characters, never shaped like a uid. */
export const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
export const isSlug = (s: string): boolean => s.length <= 32 && SLUG_RE.test(s) && !isUid(s)

/**
 * A fresh uid from `random` (fills a byte array, e.g. `crypto.getRandomValues`). 256 is a multiple of 32,
 * so `byte & 31` is unbiased; draws that miss the digit / letter rule or hit `taken` are redrawn.
 */
export function makeUid(random: (bytes: Uint8Array) => Uint8Array, taken: ReadonlySet<string> = new Set()): string {
  for (;;) {
    const id = [...random(new Uint8Array(UID_LENGTH))].map(b => UID_ALPHABET[b & 31]).join('')
    if (isUid(id) && !taken.has(id)) return id
  }
}

/** First path segments that are never a board id (pages, files, future routes); `@…` is kept for scopes. */
export const RESERVED_SEGMENTS: readonly string[] = ['widget', 'w', 'embed', 'r', 'og', 'oembed', 'assets', 'images', 'lab', 'docs', 'privacy', 'terms', 'essay']
export const isReservedSegment = (s: string): boolean => s.startsWith('@') || RESERVED_SEGMENTS.includes(s) || isUid(s)

/** A widget page request, before lookup: `key` is a slug, an old slug or a uid; `scope` is '' for the site's own. */
export interface WidgetRoute { key: string; scope: string; via: 'path' | 'short' | 'card' }

type Match = (seg: string[]) => string | undefined
/** The route table: ordered, first match wins. Each entry reads the path segments after an optional `@scope`. */
export const WIDGET_ROUTES: readonly { pattern: string; via: WidgetRoute['via']; match: Match }[] = [
  { pattern: 'widget/:key', via: 'path', match: s => (s.length === 2 && s[0] === 'widget' ? s[1] : undefined) },
  { pattern: ':uid', via: 'short', match: s => (s.length === 1 && isUid(s[0].toLowerCase()) ? s[0] : undefined) },
]

/** The widget a URL names, if any (path routes first, then the old `?card=`). */
export function widgetRoute(pathname: string, search = ''): WidgetRoute | undefined {
  let seg: string[]
  try { seg = pathname.split('/').filter(Boolean).map(decodeURIComponent) } catch { return undefined }
  const scope = seg[0]?.startsWith('@') ? seg.shift()!.slice(1).toLowerCase() : ''
  for (const r of WIDGET_ROUTES) {
    const key = r.match(seg)
    if (key) return { key: key.toLowerCase(), scope, via: r.via }
  }
  const card = new URLSearchParams(search).get('card')?.trim()
  return card ? { key: card.toLowerCase(), scope, via: 'card' } : undefined
}

/** The canonical path of a widget page: `/widget/<slug>/`, under `/@<scope>` when it has one. */
export const widgetPath = (slug: string, scope = ''): string => `${scope ? `/@${scope}` : ''}/widget/${slug}/`
/** The short link: `/<uid>` (uids are global, so it never needs a scope). */
export const shortPath = (uid: string): string => `/${uid}`

/** One row of the widget catalog (`src/widgets/catalog.ts`, generated by `scripts/widgets/ids.ts --assign`). */
export type CatalogRow = readonly [slug: string, uid: string, board: string]
export interface ResolvedWidget { slug: string; uid: string; board: string; scope: string; via: 'slug' | 'uid' | 'alias' }

/**
 * Look a route's key up: uid → slug → `aliases` (old slug → current slug, `resolveCardId`). Undefined when the
 * scope is unknown (only '' exists today) or nothing matches.
 */
export function resolveWidget(route: Pick<WidgetRoute, 'key' | 'scope'>, rows: readonly CatalogRow[], alias: (id: string) => string = id => id): ResolvedWidget | undefined {
  if (route.scope) return undefined
  const key = route.key.toLowerCase(), found = (row: CatalogRow | undefined, via: ResolvedWidget['via']) => row && { slug: row[0], uid: row[1], board: row[2], scope: '', via }
  if (isUid(key)) { const r = found(rows.find(x => x[1] === key), 'uid'); if (r) return r }
  const direct = rows.find(x => x[0] === key)
  if (direct) return found(direct, 'slug')
  const to = alias(key)
  return to !== key ? found(rows.find(x => x[0] === to), 'alias') : undefined
}

/** The address a resolved widget page shows: the canonical slug path, keeping every param but the old `card`. */
export function canonicalWidgetUrl(w: Pick<ResolvedWidget, 'slug' | 'scope'>, search: string): string {
  const q = new URLSearchParams(search)
  q.delete('card')
  const s = q.toString()
  return widgetPath(w.slug, w.scope) + (s ? `?${s}` : '')
}
